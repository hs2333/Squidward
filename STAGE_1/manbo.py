# ============================================================
# 可以随时中断的 sleep
# ============================================================

def wait(seconds):
    """
    和 time.sleep() 类似，
    但等待过程中按 Esc 可以立刻终止。
    """

    end_time = time.time() + seconds

    while time.time() < end_time:

        if keyboard.is_pressed(STOP_KEY):
            raise KeyboardInterrupt

        time.sleep(0.01)


# ============================================================
# 移动到某个音
# ============================================================

def move_to_note(note):

    if note not in NOTES:
        raise ValueError(f"未知音符: {note}")

    y = NOTES[note]

    pydirectinput.moveTo(
        X,
        y,
        duration=MOVE_DURATION
    )


# ============================================================
# 吹一个音
# ============================================================

def play_note(note, beats=1):

    move_to_note(note)

    # 用空格吹一次
    pydirectinput.press("space")

    # 等到下一个音
    wait(BEAT * beats)


# ============================================================
# 演奏整首歌
#
# 每一个元素：
#
# ("音符", 拍数)
#
# 例如：
# ("5'", 1)   = 高音5，1拍
# ("3'", 0.5) = 高音3，半拍
# ============================================================

def play_song(song):

    if len(song) == 0:
        return

    print()
    print("开始演奏")
    print("随时按 Esc 强制停止")
    print()

    # --------------------------------------------------------
    # 第一个音特殊处理
    # --------------------------------------------------------

    first_note, first_beats = song[0]

    print(f"准备第一个音：{first_note}")

    # 先移动鼠标
    move_to_note(first_note)

    print(f"等待 {FIRST_NOTE_WAIT} 秒，让游戏 UI 跟上鼠标...")

    # 只在第一个音等待
    wait(FIRST_NOTE_WAIT)

    # 再吹第一个音
    pydirectinput.press("space")

    wait(BEAT * first_beats)

    # --------------------------------------------------------
    # 后面的音正常播放
    # --------------------------------------------------------

    for index, (note, beats) in enumerate(song[1:], start=2):

        if keyboard.is_pressed(STOP_KEY):
            raise KeyboardInterrupt

        print(
            f"{index:02d}/{len(song)}  "
            f"{note:4s}  "
            f"{beats} beat"
        )

        play_note(note, beats)


